package com.portproof.core.designsystem.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * PortProof colour tokens, matched to the reference design: warm off-white canvas, white cards,
 * orange accent for progress and the main action, near-black buttons and bottom bar. Orange is used
 * as a fill only; orange text uses the darker [accentText]. Every text/background pair meets WCAG AA
 * (4.5:1); see ARCHITECTURE.md.
 */
@Immutable
data class PortProofColors(
    val canvasTop: Color,
    val canvasBottom: Color,
    /** Solid canvas colour (window background). */
    val background: Color,
    val surface: Color,
    /** Wide add button, inputs, unselected tiles. */
    val surfaceMuted: Color,
    val surfaceSunken: Color,
    val border: Color,
    val divider: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val textMuted: Color,
    /** Orange fill: gauge segments, the centre bar button, badges. Never used for text. */
    val accent: Color,
    /** Text-safe orange for captions such as "35% of schedule" and links. */
    val accentText: Color,
    /** Content on [accent] fills. */
    val onAccent: Color,
    /** Pale peach behind icons and at the foot of cards. */
    val accentContainer: Color,
    val onAccentContainer: Color,
    /** Unfilled gauge and progress segments. */
    val accentTrack: Color,
    /** Primary buttons ("Get Started"). Light in the dark theme. */
    val inverseSurface: Color,
    val onInverseSurface: Color,
    val navBar: Color,
    val onNavBar: Color,
    val onNavBarMuted: Color,
    /** Soft gradient behind detail-screen titles and the welcome artwork. */
    val headerTop: Color,
    val headerBottom: Color,
    val onHeader: Color,
    val cardGlow: Color,
    val highlightRed: Color,
    val onHighlightRed: Color,
    val highlightOrange: Color,
    val onHighlightOrange: Color,
    val highlightYellow: Color,
    val onHighlightYellow: Color,
    val success: Color,
    val successText: Color,
    val successContainer: Color,
    val warningText: Color,
    val warningContainer: Color,
    val danger: Color,
    val dangerText: Color,
    val dangerContainer: Color,
    val scrim: Color,
    val isDark: Boolean,
)

